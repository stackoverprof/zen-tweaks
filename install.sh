#!/bin/bash
# Zen Tweaks installer (macOS). Quit Zen first.
#   ./install.sh              install the mod and the startup script
#   ./install.sh --mod-only   install only the mod (CSS), no startup script
#   ./install.sh --remove     remove both
# Pick a profile with ZEN_PROFILE=/path/to/profile (default: Zen's default profile).
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
APP="${ZEN_APP:-/Applications/Zen.app}"
RES="$APP/Contents/Resources"
MODE="${1:-}"

if pgrep -f "$APP/Contents/MacOS/zen" >/dev/null; then
  echo "Quit Zen first (Cmd+Q), then run this again." >&2
  exit 1
fi

# --- 1. the mod: registered like a store mod, so it shows under Settings > Zen Mods
/usr/bin/python3 -I - "$HOME/Library/Application Support/zen" "$HERE/mod" "$MODE" <<'PY'
import sys, os, json, shutil, configparser, datetime
zen, moddir, mode = sys.argv[1], sys.argv[2], sys.argv[3]
MOD_ID = "6f1f6f2e-1b1c-4f33-9a7e-5d2f0a3c7e11"
if os.environ.get("ZEN_PROFILE"):
    profile = os.environ["ZEN_PROFILE"]
else:
    ini = configparser.ConfigParser()
    ini.read(os.path.join(zen, "profiles.ini"))
    rels = [ini[s]["Default"] for s in ini.sections() if s.startswith("Install")]
    rels = rels or [ini[s]["Path"] for s in ini.sections() if ini[s].get("Default") == "1"]
    profile = os.path.join(zen, rels[0])
chrome = os.path.join(profile, "chrome")
mods_dir = os.path.join(chrome, "zen-themes")
data_file = os.path.join(profile, "zen-themes.json")
mods = json.load(open(data_file)) if os.path.exists(data_file) else {}
mod_dir = os.path.join(mods_dir, MOD_ID)
if mode == "--remove":
    mods.pop(MOD_ID, None)
    shutil.rmtree(mod_dir, ignore_errors=True)
    print("Removed the Zen Tweaks mod from", profile)
else:
    os.makedirs(mod_dir, exist_ok=True)
    for name in ("chrome.css", "readme.md"):
        shutil.copy(os.path.join(moddir, name), os.path.join(mod_dir, name))
    mods[MOD_ID] = {"id": MOD_ID, "name": "Zen Tweaks", "description": "A slimmer, Arc-like top toolbar.",
                    "homepage": "https://github.com/stackoverprof/zen-tweaks",
                    "style": "https://raw.githubusercontent.com/stackoverprof/zen-tweaks/main/mod/chrome.css",
                    "readme": "https://raw.githubusercontent.com/stackoverprof/zen-tweaks/main/mod/readme.md",
                    "image": "", "author": "stackoverprof", "version": "1.0.0", "tags": [],
                    "enabled": mods.get(MOD_ID, {}).get("enabled", True)}
    print("Installed the Zen Tweaks mod into", profile)
os.makedirs(chrome, exist_ok=True)
json.dump(mods, open(data_file, "w"))
# Zen only rebuilds its combined stylesheet when a mod is toggled, so rebuild it here
out = "/* Zen Mods - Generated by ZenMods.\n* FILE GENERATED AT: %s\n* DO NOT EDIT THIS FILE DIRECTLY!\n* Your changes will be lost.\n*/\n" % datetime.datetime.now()
for m in mods.values():
    css = os.path.join(mods_dir, m["id"], "chrome.css")
    if m.get("enabled") is False or not os.path.exists(css):
        continue
    out += "\n/* Name: %s */\n/* Description: %s */\n/* Author: @%s */\n" % (m.get("name"), m.get("description"), m.get("author"))
    out += open(css).read()
out += "\n/* End of Zen Mods */\n"
open(os.path.join(chrome, "zen-themes.css"), "w").write(out)
PY

[ "$MODE" = "--mod-only" ] && { echo "Done (mod only). Open Zen."; exit 0; }

# --- 2. the startup script, inside Zen.app. macOS only lets Finder write into apps,
#        so this asks Finder (macOS may ask you once to allow that).
finder_block() { osascript -e "tell application \"Finder\"
$1
end tell" >/dev/null; }
finder() { osascript -e "tell application \"Finder\" to $1" >/dev/null; }
if [ "$MODE" = "--remove" ]; then
  [ -e "$RES/zen-tweaks.cfg" ] && finder "delete (POSIX file \"$RES/zen-tweaks.cfg\")"
  [ -e "$RES/defaults/pref/autoconfig.js" ] && grep -q zen-tweaks.cfg "$RES/defaults/pref/autoconfig.js" \
    && finder "delete (POSIX file \"$RES/defaults/pref/autoconfig.js\")"
  echo "Removed the startup script. Done."
  exit 0
fi
if [ -e "$RES/defaults/pref/autoconfig.js" ] && ! grep -q zen-tweaks.cfg "$RES/defaults/pref/autoconfig.js"; then
  echo "Zen.app already has a different autoconfig.js; not replacing it. Use --mod-only, or remove it first." >&2
  exit 1
fi
finder "duplicate (POSIX file \"$HERE/startup-script/zen-tweaks.cfg\") as alias to ((POSIX file \"$RES\") as alias) with replacing"
finder_block "set r to (POSIX file \"$RES\") as alias
  if not (exists folder \"defaults\" of r) then make new folder at r with properties {name:\"defaults\"}
  set d to folder \"defaults\" of r
  if not (exists folder \"pref\" of d) then make new folder at d with properties {name:\"pref\"}
  duplicate (POSIX file \"$HERE/startup-script/autoconfig.js\") as alias to folder \"pref\" of d with replacing"
echo "Installed the startup script into $APP. Done. Open Zen."
echo "Note: Zen updates replace the app, so run ./install.sh again after an update."
